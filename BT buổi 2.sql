--     "10 khách hàng thuê phim nhiều lần nhất là ai?"
--     "Giá thuê trung bình theo từng nhóm độ tuổi là bao nhiêu?"
--     "Mỗi nhân viên mang về bao nhiêu doanh thu?"
--     "Phim có bao nhiêu ngày thuê tối thiểu (rental_duration) khác nhau, mỗi loại có bao nhiêu phim?"
--     "Nhóm rating nào có thời lượng phim trung bình dài nhất?"
--     "Mỗi cửa hàng đang phục vụ bao nhiêu khách hàng?"
--     "10 khách hàng đầu tiên (theo mã) chi tiêu trung bình mỗi lần bao nhiêu?"
--     "Mỗi ngày có bao nhiêu lượt thuê phim phát sinh?"
--     "Doanh thu theo từng ngày thanh toán là bao nhiêu?"
--     "Với mỗi mức giá thuê, có bao nhiêu phim đang bán ở mức đó?"
--     "Mỗi nhân viên đã xử lý bao nhiêu đơn thuê?"
--     "Kết hợp rating và thời gian thuê tối thiểu, mỗi tổ hợp có bao nhiêu phim?"
--     "Tổng thời lượng phim (cộng dồn) theo từng nhóm rating là bao nhiêu?"

-- Phần 3: WHERE vs HAVING

--     "Những nhóm rating nào có hơn 150 phim?"
